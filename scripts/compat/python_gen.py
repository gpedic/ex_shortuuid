"""Writes test/fixtures/compat/python.tsv using Python's shortuuid package.

Usage: python3 scripts/compat/python_gen.py
"""

import importlib.metadata
import pathlib
import uuid

import shortuuid

FIXTURES = pathlib.Path(__file__).resolve().parents[2] / "test" / "fixtures" / "compat"


def read_rows(name):
    lines = (FIXTURES / name).read_text(encoding="utf-8").splitlines()
    return [line for line in lines if line and not line.startswith("#")]


def main():
    alphabets = [row.split("\t") for row in read_rows("alphabets.tsv")]
    uuids = read_rows("uuids.txt")
    version = importlib.metadata.version("shortuuid")

    out = [
        f"# Generated by scripts/compat/python_gen.py with shortuuid {version} (Python). Do not edit.",
        "# name\talphabet used\tuuid\tencoded",
    ]

    for name, alphabet in alphabets:
        su = shortuuid.ShortUUID(alphabet=alphabet)
        used = su.get_alphabet()

        for u in uuids:
            encoded = su.encode(uuid.UUID(u))
            assert str(su.decode(encoded)) == u, (name, u, encoded)
            out.append(f"{name}\t{used}\t{u}\t{encoded}")

    (FIXTURES / "python.tsv").write_text("\n".join(out) + "\n", encoding="utf-8")


if __name__ == "__main__":
    main()
