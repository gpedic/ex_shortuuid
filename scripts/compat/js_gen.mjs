// Writes test/fixtures/compat/js.tsv using the short-uuid npm package.
//
// Usage: (cd scripts/compat && npm ci && node js_gen.mjs)
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import short from "short-uuid";

const fixtures = new URL("../../test/fixtures/compat/", import.meta.url);
const { version } = createRequire(import.meta.url)("short-uuid/package.json");

const readRows = (name) =>
  readFileSync(new URL(name, fixtures), "utf8")
    .split("\n")
    .filter((line) => line && !line.startsWith("#"));

const alphabets = readRows("alphabets.tsv").map((row) => row.split("\t"));
const uuids = readRows("uuids.txt");

const out = [
  `# Generated by scripts/compat/js_gen.mjs with short-uuid ${version} (JavaScript). Do not edit.`,
  "# name\talphabet used\tuuid\tencoded",
];

for (const [name, alphabet] of alphabets) {
  const translator = short.createTranslator(alphabet);

  for (const u of uuids) {
    const encoded = translator.fromUUID(u);
    if (translator.toUUID(encoded) !== u) throw new Error(`round trip failed: ${name} ${u} ${encoded}`);
    out.push(`${name}\t${translator.alphabet}\t${u}\t${encoded}`);
  }
}

writeFileSync(new URL("js.tsv", fixtures), out.join("\n") + "\n");
