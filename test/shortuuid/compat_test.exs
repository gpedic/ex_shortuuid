defmodule ShortUUID.CompatTest do
  @moduledoc """
  Checks compatibility with other ShortUUID implementations using fixtures
  generated by `scripts/compat` (see `scripts/compat/README.md`).
  """
  use ExUnit.Case, async: true

  @fixtures Path.expand("../fixtures/compat", __DIR__)

  for impl <- ["python", "js"] do
    path = Path.join(@fixtures, "#{impl}.tsv")
    @external_resource path

    rows =
      path
      |> File.read!()
      |> String.split("\n", trim: true)
      |> Enum.reject(&String.starts_with?(&1, "#"))
      |> Enum.map(&String.split(&1, "\t"))

    for {name, [[_, alphabet, _, _] | _] = group} <- Enum.group_by(rows, &hd/1) do
      # Every row of an alphabet group must use the same alphabet.
      cases = for [_, ^alphabet, uuid, encoded] <- group, do: {uuid, encoded}
      true = length(cases) == length(group)

      module = Module.concat([__MODULE__, Macro.camelize(impl), Macro.camelize(name)])

      Module.create(
        module,
        quote(do: use(ShortUUID.Builder, alphabet: unquote(alphabet))),
        Macro.Env.location(__ENV__)
      )

      test "#{impl}: #{name} encodes and decodes like the reference implementation" do
        for {uuid, encoded} <- unquote(Macro.escape(cases)) do
          assert unquote(module).encode(uuid) == {:ok, encoded}, "encode #{uuid}"
          assert unquote(module).decode(encoded) == {:ok, uuid}, "decode #{encoded}"
        end
      end
    end
  end
end
